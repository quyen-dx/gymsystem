const bar = (pct, width = 20) => {
  const filled = Math.round((pct / 100) * width)
  return '█'.repeat(filled) + '░'.repeat(width - filled)
}

const scoreColor = (pct) => {
  if (pct >= 90) return '🟢'
  if (pct >= 70) return '🟡'
  return '🔴'
}

export const generateReport = (results) => {
  const m = results.metrics
  const now = new Date().toISOString().replace('T', ' ').slice(0, 19)
  const lines = []

  lines.push('# 🤖 AI Evaluation Report')
  lines.push('')
  lines.push(`**Date:** ${now}`)
  lines.push(`**Total Test Cases:** ${results.total}`)
  lines.push(`**Passed:** ${results.passed} | **Errors:** ${results.errors}`)
  lines.push(`**Pass Rate:** ${results.total > 0 ? ((results.passed / results.total) * 100).toFixed(1) : 0}%`)
  lines.push('')

  lines.push('## 📊 Overall Metrics')
  lines.push('')
  lines.push('| Metric | Score | Bar |')
  lines.push('|--------|------:|:---|')
  lines.push(`| **Intent Accuracy** | ${m.intentAccuracy}% | ${scoreColor(m.intentAccuracy)} ${bar(m.intentAccuracy)} |`)
  lines.push(`| Subject Accuracy | ${m.subjectAccuracy}% | ${scoreColor(m.subjectAccuracy)} ${bar(m.subjectAccuracy)} |`)
  lines.push(`| Action Accuracy | ${m.actionAccuracy}% | ${scoreColor(m.actionAccuracy)} ${bar(m.actionAccuracy)} |`)
  lines.push(`| **Tool Accuracy** | ${m.toolAccuracy}% | ${scoreColor(m.toolAccuracy)} ${bar(m.toolAccuracy)} |`)
  lines.push(`| Entity Name Accuracy | ${m.entityNameAccuracy}% | ${scoreColor(m.entityNameAccuracy)} ${bar(m.entityNameAccuracy)} |`)
  lines.push(`| Permission Accuracy | ${m.permissionAccuracy}% | ${scoreColor(m.permissionAccuracy)} ${bar(m.permissionAccuracy)} |`)
  lines.push(`| **Database Accuracy** | ${m.databaseAccuracy}% | ${scoreColor(m.databaseAccuracy)} ${bar(m.databaseAccuracy)} |`)
  lines.push(`| Hallucination Rate | ${m.hallucinationRate}% | ${bar(100 - m.hallucinationRate)} |`)
  lines.push('')
  lines.push('### ⏱ Performance')
  lines.push('')
  lines.push('| Metric | Value |')
  lines.push('|--------|------:|')
  lines.push(`| Average Response Latency | ${m.avgLatencyMs} ms |`)
  lines.push(`| P95 Latency | ${m.p95LatencyMs} ms |`)
  lines.push(`| Average Token Usage | ${m.avgTokenUsage} tokens |`)
  lines.push('')

  lines.push('## 📁 Results by Category')
  lines.push('')
  lines.push('| Category | Tests | Pass | Error | Intent Accuracy | Avg Latency |')
  lines.push('|----------|------:|-----:|------:|----------------:|------------:|')
  for (const cat of results.byCategory.sort((a, b) => b.total - a.total)) {
    lines.push(`| ${cat.name} | ${cat.total} | ${cat.pass} | ${cat.error} | ${cat.intentAccuracy}% | ${cat.avgLatencyMs}ms |`)
  }
  lines.push('')

  if (results.slowest.length > 0) {
    lines.push('## 🐌 Slowest Tests')
    lines.push('')
    lines.push('| ID | Query | Category | Latency (ms) |')
    lines.push('|----|-------|----------|-------------:|')
    for (const t of results.slowest) {
      const query = t.query.length > 60 ? t.query.slice(0, 57) + '...' : t.query
      lines.push(`| ${t.id} | ${query} | ${t.category} | ${t.latency.toFixed(0)} |`)
    }
    lines.push('')
  }

  if (results.errors.length > 0) {
    lines.push('## ❌ Errors')
    lines.push('')
    lines.push('| ID | Query | Category | Error |')
    lines.push('|----|-------|----------|-------|')
    for (const e of results.errors) {
      lines.push(`| ${e.id} | ${e.query} | ${e.category} | ${e.error} |`)
    }
    lines.push('')
  }

  const failed = results.allResults.filter((r) => r.status === 'pass' && r.scores && r.scores.intent < 1)
  if (failed.length > 0) {
    lines.push('## ⚠️ Intent Classification Issues')
    lines.push('')
    lines.push('| ID | Query | Expected Intent | Got Intent | Score |')
    lines.push('|----|-------|----------------|------------|------:|')
    for (const f of failed.slice(0, 20)) {
      lines.push(`| ${f.id} | ${f.query} | ${f.expected.intent} | ${f.result?.intent || 'N/A'} | ${f.scores.intent} |`)
    }
    if (failed.length > 20) {
      lines.push(`| ... | *${failed.length - 20} more* | | | |`)
    }
    lines.push('')
  }

  lines.push('## 📈 Test Coverage')
  lines.push('')
  const categoryCounts = {}
  for (const r of results.allResults) {
    const sub = r.subcategory || 'other'
    categoryCounts[sub] = (categoryCounts[sub] || 0) + 1
  }
  lines.push('| Subcategory | Count |')
  lines.push('|-------------|------:|')
  for (const [sub, count] of Object.entries(categoryCounts).sort((a, b) => b[1] - a[1])) {
    lines.push(`| ${sub} | ${count} |`)
  }
  lines.push('')
  lines.push('---')
  lines.push('*Report generated by AI Evaluation Suite*')

  return lines.join('\n')
}
